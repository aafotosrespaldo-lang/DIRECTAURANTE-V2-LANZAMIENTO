// Directaurante - Restaurant Panel Service Worker
const CACHE_NAME = 'directaurante-restaurant-panel-v1';
const PRECACHE_ASSETS = [
  '/restaurant-panel/',
  '/restaurant-panel/index.html',
  '/restaurant-panel/manifest.json',
  '/restaurant-panel/pwa-192x192.png',
  '/restaurant-panel/pwa-512x512.png',
  '/restaurant-panel/apple-touch-icon.png',
  '/DIRECTAURANTE ICONO.PNG'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(PRECACHE_ASSETS).catch((err) => {
        console.warn('[SW Restaurant Panel] Precache warning:', err);
      });
    }).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) {
            return caches.delete(key);
          }
        })
      );
    }).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  // Do not intercept non-GET or API calls or SSE stream endpoints
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.pathname.startsWith('/api')) return;

  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      if (cachedResponse) {
        // Return cache and update in background
        fetch(event.request)
          .then((networkResponse) => {
            if (networkResponse && networkResponse.status === 200) {
              caches.open(CACHE_NAME).then((cache) => cache.put(event.request, networkResponse));
            }
          })
          .catch(() => {});
        return cachedResponse;
      }
      return fetch(event.request).catch(() => {
        if (event.request.mode === 'navigate') {
          return caches.match('/restaurant-panel/index.html');
        }
      });
    })
  );
});
